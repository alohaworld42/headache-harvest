const dictionaries: Record<Lang, Record<TranslationKey, string>> = { de, en };

export function translate(lang: Lang, key: TranslationKey, ...args: (string | number)[]): string {
  const template = dictionaries[lang][key] ?? key;
  return args.reduce<string>(
    (text, value, index) => text.split(`{${index}}`).join(String(value)),
    template,
  );
}

export function detectLanguage(): Lang {
  if (typeof navigator === 'undefined') return 'de';
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}
